function applyTranslations(lang){
  const dict = translations[lang] || translations.ca;
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const key = el.getAttribute('data-i18n');
    if(dict[key] !== undefined){
      el.innerHTML = dict[key];
    }
  });
  if(dict.seo_title){
    document.title = dict.seo_title;
  }
  if(dict.seo_description){
    const metaDesc = document.querySelector('meta[name="description"]');
    if(metaDesc) metaDesc.setAttribute('content', dict.seo_description);
  }
  document.documentElement.setAttribute('lang', lang);
  document.documentElement.setAttribute('data-lang', lang);
  document.querySelectorAll('[data-lang-btn]').forEach(btn=>{
    btn.classList.toggle('active', btn.getAttribute('data-lang-btn') === lang);
  });
  localStorage.setItem('amfora_lang', lang);
  updateOpenStatus(lang);
}

document.querySelectorAll('[data-lang-btn]').forEach(btn=>{
  btn.addEventListener('click', ()=> applyTranslations(btn.getAttribute('data-lang-btn')));
});

/* ===================== OPEN / CLOSED STATUS ===================== */
/* Horario único: 08:00 a 20:30, todos los días de la semana */
function getScheduleFor(date){
  return [{start:8*60, end:20.5*60}];
}

function fmtTime(mins){
  const h = Math.floor(mins/60);
  const m = Math.round(mins%60);
  return String(h).padStart(2,'0') + ':' + String(m).padStart(2,'0');
}

function updateOpenStatus(lang){
  const dict = translations[lang] || translations.ca;
  const now = new Date();
  const nowMins = now.getHours()*60 + now.getMinutes();
  const ranges = getScheduleFor(now);
  let isOpen = false;
  let nextBoundary = null;

  for(const r of ranges){
    if(nowMins >= r.start && nowMins < r.end){
      isOpen = true;
      nextBoundary = r.end;
      break;
    }
  }
  if(!isOpen){
    const upcoming = ranges.find(r => nowMins < r.start);
    nextBoundary = upcoming ? upcoming.start : ranges[0].start;
  }

  const heroDot = document.getElementById('hero-dot');
  const stripDot = document.getElementById('strip-dot');
  const heroText = document.getElementById('hero-status-text');
  const stripText = document.getElementById('strip-status-text');

  if(isOpen){
    heroDot.style.background = '#7BC18B';
    stripDot.className = 'dot open';
    heroText.textContent = dict.hero_open_now;
    stripText.textContent = dict.strip_open.replace('{time}', fmtTime(nextBoundary));
  } else {
    heroDot.style.background = '#E08A6B';
    stripDot.className = 'dot closed';
    heroText.textContent = dict.hero_closed_now;
    stripText.textContent = dict.strip_closed.replace('{time}', fmtTime(nextBoundary));
  }
}

/* ===================== INIT ===================== */
/* El catalán es siempre el idioma por defecto en la primera visita.
   Si el usuario ya eligió un idioma antes, se respeta esa elección. */
(function init(){
  const saved = localStorage.getItem('amfora_lang');
  const initial = saved || 'ca';
  applyTranslations(initial);
  setInterval(()=> updateOpenStatus(document.documentElement.getAttribute('data-lang')), 60000);
})();
